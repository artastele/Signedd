                <ul class="mb-3 ps-3">
                    <li>Facilitating official SPED enrollment, class sectioning, and DepEd Learner Information System (LIS) alignment.</li>
                    <li>Structuring Individualized Education Plans (IEPs), Individual Transition Plans (ITPs), and inclusive curriculum adaptations tailored to the unique learning requirements of the child.</li>
                    <li>Conducting developmental tracking, Classroom Observation Tool (COT) evaluations, and generating official progress reports (SF9/SF10).</li>
                    <li>Enabling authenticated communication and emergency notifications between school personnel and parents/guardians.</li>
                </ul>

                <h6 class="fw-bold text-dark mt-3 mb-2">
                    <i class="bi bi-shield-check text-primary me-1"></i> 3. Security, Storage &amp; Confidentiality
                </h6>
                <p>
                    We employ rigorous technical, organizational, and physical safeguards. Passwords are cryptographically hashed using standard one-way algorithms, uploaded documents and diagnostic evaluations are stored in access-controlled environments, and data access is strictly segmented using Role-Based Access Control (RBAC). Only assigned SPED teachers, guidance counselors, and school heads assigned to the specific learner may access IEP and diagnostic records.
                </p>

                <h6 class="fw-bold text-dark mt-3 mb-2">
                    <i class="bi bi-people text-primary me-1"></i> 4. Data Sharing &amp; Third Parties
                </h6>
