                    <i class="bi bi-person-check text-primary me-1"></i> 5. Rights of the Data Subject
                </h6>
                <p>Under Republic Act No. 10173, you and your enrolled learner possess the following rights:</p>
                <ul class="mb-3 ps-3">
                    <li><strong>Right to be Informed:</strong> To understand how and why your personal information is gathered and processed.</li>
                    <li><strong>Right to Access:</strong> To request reasonable access to your records and profile data stored in the system.</li>
                    <li><strong>Right to Rectification:</strong> To request dispute or correction of any inaccurate or outdated information.</li>
                    <li><strong>Right to Object &amp; Erasure:</strong> To withdraw consent or request deletion of data subject to DepEd academic record retention policies.</li>
                </ul>

